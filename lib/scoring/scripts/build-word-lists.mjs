// Builds the T7 phonemic-fluency word lists from the BSD/macOS word files:
// web2 (Webster's Second International, 1934: public domain) for "is it in a
// dictionary", web2a for two-word terms, and propernames for first names. Only the letters T7 forms use
// are kept, so the generated modules stay small. Run on macOS/BSD:
//   pnpm --filter @workspace/scoring word-lists
// The outputs are committed (other machines may not have /usr/share/dict).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// The forms' letters (F L, S W, A H), plus B for the instruction examples (bake, big) the rules cite.
const LETTERS = ['a', 'b', 'f', 'h', 'l', 's', 'w'];
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/lexicons');
const read = (f) => readFileSync(f, 'utf8').split('\n').map((w) => w.trim()).filter(Boolean);

const words = read('/usr/share/dict/web2').filter((w) => /^[a-z]+$/.test(w) && w.length <= 14 && LETTERS.includes(w[0]));
// Two-word terms with a single meaning ("fire engine") count as one response (build doc §T7).
const compounds = read('/usr/share/dict/web2a')
  .map((w) => w.toLowerCase().replace(/-/g, ' '))
  .filter((w) => /^[a-z]+ [a-z]+$/.test(w) && LETTERS.includes(w[0]));
const names = read('/usr/share/dict/propernames').map((n) => n.toLowerCase()).filter((n) => /^[a-z]+$/.test(n) && LETTERS.includes(n[0]));

const header = (what) => `// GENERATED by scripts/build-word-lists.mjs from ${what}. Do not edit.\n`;
writeFileSync(
  path.join(OUT, 'dictionary.generated.ts'),
  `${header("/usr/share/dict/web2 (Webster's 2nd, 1934, public domain); letters " + LETTERS.join(', ').toUpperCase())}export const DICTIONARY_WORDS = ${JSON.stringify(words.join(' '))};\nexport const DICTIONARY_COMPOUNDS = ${JSON.stringify([...new Set(compounds)].join('|'))};\n`,
);
writeFileSync(
  path.join(OUT, 'first-names.generated.ts'),
  `${header('/usr/share/dict/propernames; letters ' + LETTERS.join(', ').toUpperCase())}export const FIRST_NAMES = ${JSON.stringify(names.join(' '))};\n`,
);
console.log(`dictionary: ${words.length} words, ${new Set(compounds).size} compounds · first names: ${names.length}`);
